def find(lines: list[str], head: str, start: int = 0) -> int:
    for i in range(start, len(lines)):
        if lines[i].startswith(head):
            return i
    raise SystemExit(f"제목을 찾지 못했어요: {head}")


def main() -> None:
    lines = SRC.read_text(encoding="utf-8").splitlines()
    first = find(lines, "1. 한국사 사건")
    intro = [l for l in lines[:first] if l.strip() and not l.startswith("틀린 곳은")]
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("검수_*.txt"):
        old.unlink()
    total = len(PARTS)
    for k, (fname, desc, a, b, asks) in enumerate(PARTS, 1):
        s = find(lines, a)
        e = find(lines, b) if b else len(lines)
        body = lines[s:e]
        # 사건을 시대 중간에서 자를 때는 큰 제목(1. 한국사 사건)을 다시 달아 줘요
        if not (a[:1].isdigit() and a[1:3] == ". "):
            sec = next(l for l in reversed(lines[:s]) if l[:1].isdigit() and l[1:3] == ". ")
            body = [sec + " (이어서)", ""] + body
        head = request_block(k, total, desc, asks) + [""] + intro + [""]
        path = OUT / f"검수_{k}_{fname}.txt"
        path.write_text("\n".join(head + body).rstrip() + "\n", encoding="utf-8")
        print(f"{path.name}: {len(body)}줄, {path.stat().st_size // 1024}KB")


if __name__ == "__main__":
    main()
